    #[test]
    fn migration_follows_direction_and_respects_the_dial_handling_slot() {
        let draft = parse(json!({"congestion": "bbr", "udpHop": {"ports": "20000-50000", "interval": 30}}));
        assert!(draft.has_legacy_udp_hop());

        // Inbound: a listener never read udpHop — removed, the chain untouched.
        let (mut inbound, mut udp) = (draft.clone(), vec![layer("salamander")]);
        assert_eq!(
            migrate_legacy_udp_hop(&mut inbound, &mut udp, StreamDirection::Inbound),
            Ok(LegacyUdpHopMigration::RemovedServerSide)
        );
        assert!(!inbound.has_legacy_udp_hop());
        assert_eq!(udp, vec![layer("salamander")]);
        assert_eq!(quic_params_to_value(&inbound), json!({"congestion": "bbr"}));

        // Outbound: the layer goes to udp[0], ahead of the other masks.
        let (mut outbound, mut udp) = (draft.clone(), vec![layer("salamander")]);
        assert_eq!(
            migrate_legacy_udp_hop(&mut outbound, &mut udp, StreamDirection::Outbound),
            Ok(LegacyUdpHopMigration::Migrated { dropped_keys: Vec::new() })
        );
        assert!(!outbound.has_legacy_udp_hop());
        assert_eq!(udp.len(), 2);
        assert_eq!(udp[0].layer_type, "udphop");
        assert_eq!(udp[0].settings["remotePorts"], "20000-50000");
        assert_eq!(udp[1], layer("salamander"));

        // Outbound with another dial-handling mask anywhere: refused, nothing changed.
        for existing in ["udphop", " XICMP "] {
            let (mut outbound, mut udp) = (draft.clone(), vec![layer("noise"), layer(existing)]);
            let error = migrate_legacy_udp_hop(&mut outbound, &mut udp, StreamDirection::Outbound).unwrap_err();
            assert!(error.contains("finalmask.udp[1] is already a"), "{error}");
            assert!(outbound.has_legacy_udp_hop());
            assert_eq!(udp.len(), 2);
        }

        // Outbound without ports: the old dialer did not hop — removed, no layer.
        let mut inactive = parse(json!({"udpHop": {"interval": 30}}));
        let mut udp = Vec::new();
        assert_eq!(
            migrate_legacy_udp_hop(&mut inactive, &mut udp, StreamDirection::Outbound),
            Ok(LegacyUdpHopMigration::RemovedInactive)
        );
        assert!(udp.is_empty() && !inactive.has_legacy_udp_hop());

        // A broken shape is refused on an outbound, removed on an inbound (it is dead there).
        let broken = parse(json!({"udpHop": "20000-50000"}));
        assert!(migrate_legacy_udp_hop(&mut broken.clone(), &mut Vec::new(), StreamDirection::Outbound).is_err());
        assert_eq!(
            migrate_legacy_udp_hop(&mut broken.clone(), &mut Vec::new(), StreamDirection::Inbound),
            Ok(LegacyUdpHopMigration::RemovedServerSide)
        );
        assert!(migrate_legacy_udp_hop(&mut QuicParamsDraft::default(), &mut Vec::new(), StreamDirection::Inbound).is_err());
    }

